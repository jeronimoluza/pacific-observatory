"""WFP/VAM commodity label -> COICOP-2018 leaf, hand-written at onboarding.

The World Food Programme publishes one English commodity vocabulary across
every country panel on HDX, so the five regional ``_shared.<region>.
wfp_food_prices`` modules share a single map rather than each carrying a
near-identical copy. ``coicop_classification: source_curated`` on every
``wfp_prices`` manifest: these are clean, stable commodity labels ("Millet",
"Rice (imported)"), not retail SKU strings, so the downstream classifier --
trained on messy supermarket names -- is the wrong tool.

Scope is COICOP divisions 01 and 02 ONLY. WFP panels carry a large non-food
block (fuel, wages, exchange rates, transport fares, soap, batteries,
fertilizer, milling fees, internet bundles); those item names are
deliberately absent from the map so the fetcher drops them with a logged
warning instead of forcing them into a food leaf.

Judgment calls, and why an item is ABSENT rather than guessed:

* Fresh vs preserved is a different leaf, and WFP's label does not always
  say which. Only fish whose label states the preservation state is mapped
  ("Fish (dry)", "Fish (smoked)", "Fish (salted)" -> 01.1.3.2.9; "Fish
  (fresh)" -> 01.1.3.1.9). Small market fish sold by the heap -- kapenta,
  matemba, usipa, utaka, bonya -- are sold both fresh and sun-dried
  depending on the market, so they are left unmapped, as are the
  unqualified "Fish (appolo)" and the two mixed-species labels
  "Fish (barbel, sole)" and "Fish (mullet, catfish)".
* Paddy / unmilled rice is not 01.1.1.1.2: that leaf is "dried grains of
  rice ... husked / semi- or wholly milled / parboiled". No paddy leaf
  exists in division 01, so "Rice (paddy)", "Rice (paddy, long grain,
  local)", "Rice (ordinary, unmilled)" and "Rice (glutinous, unmilled)"
  are unmapped.
* "Sugar" is mapped to cane sugar (01.1.8.1.1). Measured: 35 of the 36
  panels carrying the unqualified label are cane-sugar markets; Kyrgyzstan
  is the one beet-sugar exception, knowingly mis-assigned rather than
  dropping 2,436 rows across 36 countries.
* "Water (drinking)" is unmapped: the same label carries "Cubic meter"
  rows (piped water supply, COICOP 04.4.1) and "1.5 L" rows (bottled
  water, 01.2.5.0.0). A name-keyed map cannot split them.
* "Tea", "Meat", "Chicken", "Beans (green)", "Beans (long)" and
  "Amaranthus" are unmapped: each spans two leaves across the panels that
  carry it (green vs black tea; live bird vs poultry meat; fresh vs dried;
  grain vs leaf amaranth).
* Oilseeds pressed for oil rather than eaten ("Niger seed", "Rape seed",
  "Lin seed") are unmapped, as are the blended food-aid flours
  ("Corn Soy Blend (CSB++, food aid)") and "Kocho" (fermented enset).
* Live camels and donkeys and terrestrial snails map to 01.1.2.1.9, camel
  milk to 01.1.4.1.4. Both are real taxonomy leaves but sit outside the
  257-leaf division-01/02 measurement grid, so they add rows without
  adding grid cells.
"""

